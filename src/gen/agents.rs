//! The AGENTS.md block (gen T3, root V14): a table of the generated steps,
//! between markers the repository places. Without the markers AGENTS.md is
//! the repository's alone and gen leaves it untouched.

use crate::catalog::Check;
use std::fmt::Write as _;

/// The file the block lives in.
pub const AGENTS: &str = "AGENTS.md";

const BEGIN: &str = "<!-- BEGIN pklith -->";
const END: &str = "<!-- END pklith -->";

/// `doc` with the text between its markers replaced by the table for
/// `checks`; `None` when `doc` has no pair of markers.
#[must_use]
pub fn splice(doc: &str, checks: &[&Check]) -> Option<String> {
    let start = doc.find(BEGIN)?;
    let end = doc.get(start..)?.find(END)? + start;
    let (head, tail) = (doc.get(..start)?, doc.get(end..)?);
    Some(format!("{head}{BEGIN}\n{}{tail}", table(checks)))
}

/// One row per check, in emit order: its id, the files its runner sees,
/// whether it fixes, and what a failure means.
fn table(checks: &[&Check]) -> String {
    let mut out = String::from(
        "<!-- generated by `pkli gen` from .pklith; do not edit -->\n| check | files | fixes | when it fails |\n|---|---|---|---|\n",
    );
    for check in checks {
        let fixes = if check.fix.is_some() { "yes" } else { "-" };
        let msg = check.msg.replace('|', "\\|");
        let _ = writeln!(
            out,
            "| `{}` | {} | {fixes} | {msg} |",
            check.id,
            reach(check)
        );
    }
    out
}

/// The files a check's runner sees, as backticked globs.
fn reach(check: &Check) -> String {
    if check.globs.is_empty() {
        return "whole tree".to_owned();
    }
    let globs: Vec<String> = check.globs.iter().map(|g| format!("`{g}`")).collect();
    globs.join(" ")
}

#[cfg(test)]
mod tests {
    use super::splice;
    use crate::registry::Error;

    const DOC: &str =
        "# Agents\n\nprose\n<!-- BEGIN pklith -->\nold\n<!-- END pklith -->\nmore prose\n";

    const WANT: &str = "# Agents\n\nprose\n<!-- BEGIN pklith -->\n<!-- generated by `pkli gen` from .pklith; do not edit -->\n| check | files | fixes | when it fails |\n|---|---|---|---|\n| `shellcheck` | `**/*.sh` `**/*.bash` `.envrc` | - | shell script finding |\n| `no-broken-symlinks` | whole tree | - | a symlink points nowhere |\n<!-- END pklith -->\nmore prose\n";

    /// The block between the markers is the table; the prose around it
    /// stays; without markers there is nothing to do.
    #[test]
    fn the_block_is_spliced_between_the_markers() -> Result<(), Error> {
        let catalog = crate::catalog::builtin()?;
        let pick = |id: &str| catalog.iter().find(|c| c.id == id);
        let checks: Vec<_> = ["shellcheck", "no-broken-symlinks"]
            .iter()
            .filter_map(|id| pick(id))
            .collect();
        assert_eq!(splice(DOC, &checks).as_deref(), Some(WANT));
        assert_eq!(splice("# Agents\n", &checks), None);
        assert_eq!(
            splice("<!-- END pklith -->\n<!-- BEGIN pklith -->\n", &checks),
            None
        );
        Ok(())
    }
}
