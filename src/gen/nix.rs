//! `nix/pklith.nix` (gen T2): the packages the generated steps run, so a
//! dev shell provides exactly the tools the gate calls.

use crate::catalog::Check;
use std::fmt::Write as _;

/// The generated nix file, from the repository root.
pub const NIX: &str = "nix/pklith.nix";

/// A nix function from pklith's catalog namespace (nixpkgs plus the tools
/// nixpkgs lacks; `lib.devShell` passes it) to the packages `checks` run:
/// each `nix` attribute once, sorted (root V3), none for checks hk runs
/// itself. Written as nixfmt writes it (V5), with no system in it (root
/// V21).
#[must_use]
pub fn nix(checks: &[&Check]) -> String {
    let mut attrs: Vec<&str> = checks
        .iter()
        .map(|c| c.nix.as_str())
        .filter(|a| !a.is_empty())
        .collect();
    attrs.sort_unstable();
    attrs.dedup();
    let list = list(&attrs);
    format!(
        "# generated by `pkli gen` from .pklith; do not edit\n# The packages the generated hk steps run: `import ./nix/pklith.nix catalog`,\n# with pklith's catalog namespace (nixpkgs plus the tools nixpkgs lacks).\ncatalog: {list}\n"
    )
}

/// A nix list as nixfmt writes it: `[ ]` when empty, one item per line.
fn list(attrs: &[&str]) -> String {
    if attrs.is_empty() {
        return "[ ]".to_owned();
    }
    let mut out = String::from("[\n");
    for attr in attrs {
        let _ = writeln!(out, "  catalog.{attr}");
    }
    out + "]"
}

#[cfg(test)]
mod tests {
    use super::nix;
    use crate::registry::Error;

    const WANT: &str = "# generated by `pkli gen` from .pklith; do not edit
# The packages the generated hk steps run: `import ./nix/pklith.nix catalog`,
# with pklith's catalog namespace (nixpkgs plus the tools nixpkgs lacks).
catalog: [
  catalog.clippy
  catalog.microlith
  catalog.shellcheck
]
";

    /// Each attribute once, sorted; hk's own checks need no package.
    #[test]
    fn the_nix_list_holds_each_package_once() -> Result<(), Error> {
        let catalog = crate::catalog::builtin()?;
        let pick = [
            "shellcheck",
            "mth-fmt",
            "mth-check",
            "clippy",
            "trailing-whitespace",
        ];
        let checks: Vec<_> = catalog
            .iter()
            .filter(|c| pick.contains(&c.id.as_str()))
            .collect();
        assert_eq!(nix(&checks), WANT);
        assert!(nix(&[]).ends_with("catalog: [ ]\n"));
        Ok(())
    }

    /// V5: nixfmt leaves the emitted file as it is, empty or not.
    #[test]
    fn nixfmt_accepts_the_emitted_file() -> Result<(), Box<dyn std::error::Error>> {
        let dir = std::env::temp_dir().join(format!("pklith-nix-{}", std::process::id()));
        std::fs::create_dir_all(&dir)?;
        let catalog = crate::catalog::builtin()?;
        for (name, text) in [
            ("full.nix", nix(&catalog.iter().collect::<Vec<_>>())),
            ("empty.nix", nix(&[])),
        ] {
            std::fs::write(dir.join(name), text)?;
            let mut cmd = crate::proc::command("nixfmt", &dir);
            cmd.args(["--check", name]);
            crate::proc::output(&mut cmd)?;
        }
        Ok(std::fs::remove_dir_all(dir)?)
    }
}
